"""Transforms added in this pipeline on top of the verified base steps: the two design corrections (R3 positive part,
R4-m dwell waiver), the generic CMake test registration, the experiment-driver pass-through of the fixes preset,
and the preset files. Every target comes from discovery (R[...])."""
import os
import re

from fixlib import rep, write_file, GateFailure

# ordered repair units; every preset is a union of units (+ diag_log)
UNITS = {
    'FX1': ['r1a_reachable_cone', 'r1b_continuous_slack', 'r1c_heading_memory', 'r1d_feasible_cone'],
    'FX2': ['r2a_kappa_decay', 'r2b_kappa_local_excluded'],
    'FX3': ['r3_relevant_trigger'],
    'FX4': ['r4_switch_hysteresis'],
    'FX5': ['r5_mode_gating'],
    'FX6': ['s1_eps_constraint'],
}
ALL_FLAGS = [f for u in UNITS.values() for f in u] + ['r4m_dwell_free_only', 'diag_log']
LADDER = [('diag_only', []), ('v1_r1', ['FX1']), ('v1_r2', ['FX1', 'FX2']), ('v1_r3', ['FX1', 'FX2', 'FX3']),
          ('v1_r4', ['FX1', 'FX2', 'FX3', 'FX4']), ('v1_r5', ['FX1', 'FX2', 'FX3', 'FX4', 'FX5'])]


def flags_of(units, r4m=False, diag=True):
    on = {f for u in units for f in UNITS[u]}
    if r4m and 'FX4' in units:
        on.add('r4m_dwell_free_only')
    if diag:
        on.add('diag_log')
    return {f: f in on for f in ALL_FLAGS}


def preset_text(name, flags, note):
    lines = ['# [fixes] preset %s: %s' % (name, note),
             '# Generated by the fix_coupling_artifacts pipeline. Loaded with fixes_file:=%s; every flag false = thesis-frozen-v1.' % name,
             'fixes:']
    lines += ['  %s: %s' % (f, 'true' if flags[f] else 'false') for f in ALL_FLAGS]
    return '\n'.join(lines) + '\n'


def write_preset(R, name, flags, note):
    write_file(os.path.join(R['fixes_dir'], name + '.yaml'), preset_text(name, flags, note))


def default_presets():
    P = {'all_off': (flags_of([], diag=False), 'every flag false (identical to thesis-frozen-v1)'),
         'diag_only': (flags_of([]), 'extended diagnostics only, no behavioural change')}
    for name, units in LADDER[1:]:
        P[name] = (flags_of(units), 'V1 ladder step: %s' % '+'.join(units))
    P['all_on'] = (flags_of(['FX1', 'FX2', 'FX3', 'FX4', 'FX5']), 'all high-priority repairs FX1-FX5 (FX6/S1 is evaluated separately)')
    P['s1_only'] = (flags_of(['FX6']), 'FX6 epsilon-constraint only')
    return P


# ---------------------------------------------------------------- C++: the two design corrections
def r3_positive_part(R):
    C = R['core_cpp']
    rep(C, '''    // [fix R3] A weight increase off the current path can never make another route better, and a decrease on the
    // path keeps it optimal. Only (i) a net increase of the remaining path cost or (ii) the total decrease over the
    // off-path cached edges can change the decision; each is compared with eps_w.''',
        '''    // [fix R3] A weight increase off the current path can never make another route better, and a decrease on the
    // path keeps it optimal. Only (i) the summed increases on the remaining path or (ii) the summed decreases over the
    // off-path cached edges can change the decision; each is compared with eps_w. Both sums take positive parts:
    // a decrease on one remaining edge must not mask an increase on another (the route sharing the decreased edge
    // and bypassing the increased one gains the full increase).''')
    rep(C, '''      up += w - e.w;
      up_nk += (w - kNow(e.from_cell, e.to_cell)) - (e.w - e.kappa);''',
        '''      up += std::max(0.0, w - e.w);
      up_nk += std::max(0.0, (w - kNow(e.from_cell, e.to_cell)) - (e.w - e.kappa));''')


def r4m_dwell_waiver(R):
    rep(R['switches_h'], '''    bool r4_switch_hysteresis = false;     // R4 geometric switch only if cheaper by eps_w and T_g after the last switch
''', '''    bool r4_switch_hysteresis = false;     // R4 geometric switch only if cheaper by eps_w and T_g after the last switch
    bool r4m_dwell_free_only = false;      // R4-m the R4 dwell applies only in threat-free mode; the eps_w margin always
''')
    rep(R['coupling_cpp'], '''r4_switch_hysteresis || r5_mode_gating ||''',
        '''r4_switch_hysteresis || r4m_dwell_free_only ||
           r5_mode_gating ||''')
    rep(R['core_h'], '''    int is_switch = 0, accepted = 1, forced = 0;
''', '''    int is_switch = 0, accepted = 1, forced = 0, dwell_applied = 0;
''')
    C = R['core_cpp']
    rep(C, '''    double last_switch_t;
''', '''    double last_switch_t;
    bool free_now; // [fix R4-m] threat-free mode of the local layer when the search starts
''')
    rep(C, '''      last_switch_t = last_switch_t_;
''', '''      last_switch_t = last_switch_t_;
      free_now = free_mode_;
''')
    rep(C, '''        keep_old = !sd.forced && !(sd.C_new <= sd.C_old - cfg_.c.eps_w && sd.dwell_left <= 0.0);
''', '''        // [fix R4-m] under a threat (not in free mode) only the margin applies, so a switch away from a moving
        // obstacle is never held back by the dwell
        const bool dwell_applies = !cfg_.sw.fx.r4m_dwell_free_only || free_now;
        sd.dwell_applied = dwell_applies ? 1 : 0;
        keep_old = !sd.forced && !(sd.C_new <= sd.C_old - cfg_.c.eps_w && (!dwell_applies || sd.dwell_left <= 0.0));
''')
    N = R['node_cpp']
    rep(N, '''    sw.fx.r4_switch_hysteresis = param(nh, "fixes/r4_switch_hysteresis", false);
''', '''    sw.fx.r4_switch_hysteresis = param(nh, "fixes/r4_switch_hysteresis", false);
    sw.fx.r4m_dwell_free_only = param(nh, "fixes/r4m_dwell_free_only", false);
''')
    rep(N, '''"r3 %d r4 %d r5 %d s1 %d diag %d",''', '''"r3 %d r4 %d r4m %d r5 %d s1 %d diag %d",''')
    rep(N, '''sw.fx.r4_switch_hysteresis,
               sw.fx.r5_mode_gating, sw.fx.s1_eps_constraint, sw.fx.diag_log);''',
        '''sw.fx.r4_switch_hysteresis,
               sw.fx.r4m_dwell_free_only, sw.fx.r5_mode_gating, sw.fx.s1_eps_constraint, sw.fx.diag_log);''')
    rep(N, '''        << ", r5_mode_gating: " << sw.fx.r5_mode_gating''',
        '''        << ", r4m_dwell_free_only: " << sw.fx.r4m_dwell_free_only << ", r5_mode_gating: " << sw.fx.r5_mode_gating''')
    rep(N, '''"t,reason,is_switch,accepted,forced,C_old,C_new,dwell_left,up,down,n_on,n_off\\n"''',
        '''"t,reason,is_switch,accepted,forced,C_old,C_new,dwell_left,up,down,n_on,n_off,dwell_applied\\n"''')
    rep(N, '''<< num(d.down) << "," << d.n_on << "," << d.n_off << "\\n";''',
        '''<< num(d.down) << "," << d.n_on << "," << d.n_off << "," << d.dwell_applied << "\\n";''')
    # R1b alone stalled at lambda = 0 in the offline tests (zero-width ray blocked): warn when R1d is missing
    rep(N, '''    sw.fx.diag_log = param(nh, "fixes/diag_log", false);
''', '''    sw.fx.diag_log = param(nh, "fixes/diag_log", false);
    if (sw.fx.r1b_continuous_slack && !sw.fx.r1d_feasible_cone)
      ROS_WARN("[jps_vo] fixes: r1b_continuous_slack without r1d_feasible_cone stalled at lambda = 0 in the offline "
               "tests; enable r1d_feasible_cone with it");
''')
    if 'invariant' not in open(N).read():
        raise GateFailure('Gate-1 edit', 'node invariant check not found after the R2a edit')


# ---------------------------------------------------------------- CMake: register the new offline tests
def cmake_tests(R, new_tests):
    s = open(R['cmake']).read()
    m = re.search(r'foreach\(\s*t\s+([^)]*)\)', s)
    names = m.group(1).split()
    add = [t for t in new_tests if t not in names]
    rep(R['cmake'], m.group(0), 'foreach(t %s)' % ' '.join(names + add))


# ---------------------------------------------------------------- experiment drivers: fixes preset pass-through
def start_script(R):
    S = R['start_script']
    s = open(S).read()
    m = re.search(r'^(PRE_ROTATE=\$\{PRE_ROTATE:-\w+\})\n', s, flags=re.M)
    if not m:
        raise GateFailure('Gate-1 edit', 'PRE_ROTATE default not found in %s' % S)
    rep(S, m.group(0), m.group(0) + '''FIXES_FILE=${FIXES_FILE:-}            # engineering fixes preset (config/fixes/<name>.yaml); "" = thesis-frozen-v1
FIXES_ARG=""; [ -n "$FIXES_FILE" ] && FIXES_ARG=" fixes_file:=$FIXES_FILE"
''')
    # the argument is appended only when a preset is set, so the default command line is unchanged
    # ('$PRE_ROTATE"$FIXES_ARG"' stays one word: the unquoted and the double-quoted expansion are adjacent)
    rep(S, "pre_rotate_yaw:='$PRE_ROTATE' 2>&1", "pre_rotate_yaw:='$PRE_ROTATE\"$FIXES_ARG\"' 2>&1")


def batch_script(R):
    B = R['batch_script']
    rep(B, '''MAX_ATTEMPTS=${MAX_ATTEMPTS:-3}
''', '''MAX_ATTEMPTS=${MAX_ATTEMPTS:-3}
FIXES_FILE=${FIXES_FILE:-}                # engineering fixes preset (config/fixes/<name>.yaml); "" = thesis-frozen-v1
''')
    rep(B, '''driver_commit: '$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null)'
EOF
''', '''driver_commit: '$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null)'
EOF
  [ -n "$FIXES_FILE" ] && meta_set fixes_file "$FIXES_FILE"
''')
    rep(B, '''LOG_DIR=$LOG_DIR GROUP=$G PLANNER_MODE=coupled''', '''LOG_DIR=$LOG_DIR GROUP=$G FIXES_FILE=$FIXES_FILE PLANNER_MODE=coupled''')
